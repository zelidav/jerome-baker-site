"""Animation frames for the humanoid JB Crew (the bench hit and the shop antics).

Frames are made once in ~/code/jbsite-work/anim (gen_frames.py: nano-banana from each character's art,
BiRefNet cutouts). This trims them, writes assets/anim/<img>/<pose>.webp and js/anim-data.js with each
frame's size and, for the smoking poses, where the mouth is (as a fraction of the frame)."""
import json, os
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(os.path.expanduser('~/code/jbsite-work/anim/cut'))
OUT = ROOT / 'assets' / 'anim'
CHARS = {'lion': 'torch', 'chimp': 'major-tom-tom', 'bot': 'baker-bot', 'alien': 'gray',
         'devil': 'lil-lucky', 'gorilla': 'public-enemy', 'pumpkin': 'jack', 'cy': 'cy'}
POSES = ['stand', 'walk1', 'walk2', 'walk3', 'lean', 'hit', 'exhale', 'cough', 'pose', 'stroke1', 'stroke2',
         'hop', 'dizzy', 'carry', 'reach', 'punch']
# the poses came out at different sizes; drawn at standing height x this, a character stays the same size
SCALE = {'stand': 1, 'walk1': .97, 'walk2': .97, 'walk3': .99, 'lean': .9, 'hit': .88, 'exhale': 1, 'cough': .8,
         'pose': 1, 'stroke1': 1, 'stroke2': 1, 'hop': .92, 'dizzy': .86, 'carry': 1.08, 'reach': .82, 'punch': .82}
MOUTH = {'lean', 'hit', 'exhale', 'cough'}
H = 520


def mouth(im):
    """Frames face right: the mouth is the furthest-right point of the face, a fifth to two fifths down."""
    a = im.getchannel('A').load()
    w, h = im.size
    best = (0, int(h * .25))
    for y in range(int(h * .12), int(h * .4)):
        for x in range(w - 1, -1, -1):
            if a[x, y] > 128:
                if x > best[0]:
                    best = (x, y)
                break
    return [round(best[0] / w, 3), round(best[1] / h, 3)]


def main():
    data = {}
    for img, slug in CHARS.items():
        frames = {}
        for pose in POSES:
            src = SRC / f'{img}_{pose}.png'
            if not src.exists():
                continue
            out = OUT / img / f'{pose}.webp'
            im = Image.open(src).convert('RGBA')
            im = im.crop(im.getchannel('A').point(lambda v: 255 if v > 40 else 0).getbbox())
            im = im.resize((round(im.width * H / im.height), H), Image.LANCZOS)
            out.parent.mkdir(parents=True, exist_ok=True)
            if not out.exists() or src.stat().st_mtime > out.stat().st_mtime:
                im.save(out, 'WEBP', quality=82, method=3)
            f = {'w': im.width, 'h': im.height, 's': SCALE[pose]}
            if pose in MOUTH:
                f['m'] = mouth(im)
            frames[pose] = f
        data[slug] = {'img': img, 'frames': frames}
    (ROOT / 'js' / 'anim-data.js').write_text('/* generated by tools/build_anim.py */\nwindow.JB_ANIM = '
                                             + json.dumps(data, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(len(data), 'characters,', sum(len(d['frames']) for d in data.values()), 'frames')


if __name__ == '__main__':
    main()
