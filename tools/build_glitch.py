"""Heading glitch styles. Run `python tools/build_glitch.py` to rewrite css/glitch.css.

Five looks, one per page (body[data-glitch]); js/glitch.js marks the headings. The random clip
keyframes are generated here with a fixed seed, the way the SCSS-loop versions of these effects
build theirs, so the CSS is reproducible and needs no preprocessor.

  8bit    CSS Glitch: pixel font, choppy stepped slices in yellow and red
  text    Glitch Text: constant sliced shimmer with thin red/blue fringes
  psycho  Psycho Glitch: extruded type, quiet, then bursts of neon slice-bars
  hello   Hello: chunky red/teal offset type that wiggles on hover and now and then
  clip    Glitch w/ clip-path: red/teal/blue layers sliced with polygons on hover and in bursts
"""
import os
import random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rnd = random.Random(1991)


def r(a, b):
    return rnd.randint(a, b)


def slices(name, n, dx, idle=0.0, hidden='inset(50% 0 50% 0)'):
    """Random horizontal-band keyframes. With idle > 0 the layer stays hidden for that share of the loop."""
    out = [f'@keyframes {name}{{']
    if idle:
        out.append(f'0%,{idle * 100:.0f}%{{clip-path:{hidden};transform:none}}')
    span = 1 - idle
    for k in range(n + 1):
        pct = (idle + span * k / n) * 100
        top = r(0, 92)
        bot = max(0, 100 - top - r(3, 22))
        out.append(f'{pct:.1f}%{{clip-path:inset({top}% 0 {bot}% 0);transform:translate({r(-dx, dx)}px,{r(-2, 2)}px)}}')
    out.append('}')
    return '\n'.join(out)


def polys(name, n, dx, idle=0.0):
    """Slanted polygon slices for the clip-path look."""
    out = [f'@keyframes {name}{{']
    if idle:
        out.append(f'0%,{idle * 100:.0f}%{{clip-path:polygon(0 0,0 0,0 0,0 0);transform:none}}')
    span = 1 - idle
    for k in range(n + 1):
        pct = (idle + span * k / n) * 100
        a, b = r(0, 80), r(0, 80)
        h = r(6, 26)
        out.append(f'{pct:.1f}%{{clip-path:polygon(0 {a}%,100% {b}%,100% {b + h}%,0 {a + h}%);transform:translateX({r(-dx, dx)}px)}}')
    out.append('}')
    return '\n'.join(out)


CSS = f"""/* Heading glitches. Generated by tools/build_glitch.py, do not edit by hand. */
.glt{{position:relative;display:inline-block}}
.glt::before,.glt::after{{content:attr(data-text);position:absolute;inset:0;padding:inherit;box-sizing:border-box;white-space:inherit;color:inherit;pointer-events:none;background:none;clip-path:inset(50% 0 50% 0)}}

/* 8bit: CSS Glitch */
[data-glitch="8bit"] .glt{{font-family:"Silkscreen",var(--display);font-weight:700;letter-spacing:.01em}}
[data-glitch="8bit"] .glt::before{{color:#FFF100;text-shadow:3px 0 #0A0A0A;animation:g8a 2.6s steps(1) infinite;animation-delay:var(--gd,0s)}}
[data-glitch="8bit"] .glt::after{{color:#DA2342;text-shadow:-3px 0 #0A0A0A;animation:g8b 3.4s steps(1) infinite alternate-reverse;animation-delay:var(--gd,0s)}}
{slices('g8a', 18, 6, idle=.45)}
{slices('g8b', 18, 6, idle=.5)}

/* text: Glitch Text */
[data-glitch="text"] .glt::before{{left:2px;text-shadow:-2px 0 #DA2342;animation:gta 3s linear infinite alternate-reverse;animation-delay:var(--gd,0s)}}
[data-glitch="text"] .glt::after{{left:-2px;text-shadow:-2px 0 #2A3B8E,2px 2px #DA2342;animation:gtb 2.2s linear infinite alternate-reverse;animation-delay:var(--gd,0s)}}
{slices('gta', 20, 3)}
{slices('gtb', 20, 3)}

/* psycho: Psycho Glitch */
[data-glitch="psycho"] .glt{{text-shadow:1px 1px 0 #0A0A0A,2px 2px 0 #05B48F,3px 3px 0 #05B48F,4px 4px 0 #05B48F,5px 5px 0 #05B48F,6px 6px 0 #0A0A0A}}
[data-glitch="psycho"] .glt::before{{color:#FF2EC4;text-shadow:none;animation:gpa 4.2s steps(1) infinite;animation-delay:var(--gd,0s)}}
[data-glitch="psycho"] .glt::after{{color:#3BFF6F;text-shadow:none;animation:gpb 5.1s steps(1) infinite;animation-delay:var(--gd,0s)}}
{slices('gpa', 10, 28, idle=.82)}
{slices('gpb', 10, 28, idle=.86)}

/* hello: Hello */
[data-glitch="hello"] .glt{{text-shadow:-4px -2px 0 #DA2342,4px 3px 0 #05B48F;animation:ghw 7s linear infinite;animation-delay:var(--gd,0s)}}
[data-glitch="hello"] .glt::before,[data-glitch="hello"] .glt::after{{content:none}}
[data-glitch="hello"] .glt:hover,[data-glitch="hello"] :hover>.glt{{animation:ghh .3s steps(2) infinite}}
@keyframes ghw{{0%,93%,100%{{transform:none;text-shadow:-4px -2px 0 #DA2342,4px 3px 0 #05B48F}}94%{{transform:skewX(-14deg);text-shadow:-8px 0 0 #DA2342,6px 2px 0 #05B48F}}96%{{transform:skewX(10deg) translateX(4px);text-shadow:5px -3px 0 #DA2342,-7px 3px 0 #05B48F}}98%{{transform:skewX(-4deg);text-shadow:-3px 2px 0 #DA2342,3px -2px 0 #05B48F}}}}
@keyframes ghh{{0%{{transform:skewX(-10deg);text-shadow:-7px -2px 0 #DA2342,7px 3px 0 #05B48F}}50%{{transform:skewX(8deg) translateX(3px);text-shadow:6px 2px 0 #DA2342,-6px -3px 0 #05B48F}}100%{{transform:none}}}}

/* clip: Glitch w/ clip-path */
[data-glitch="clip"] .glt::before{{color:#DA2342;animation:gca 6s steps(1) infinite;animation-delay:var(--gd,0s)}}
[data-glitch="clip"] .glt::after{{color:#05B48F;animation:gcb 6s steps(1) infinite;animation-delay:var(--gd,0s)}}
[data-glitch="clip"] .glt:hover,[data-glitch="clip"] :hover>.glt{{text-shadow:3px 3px 0 #2A3B8E,-3px -2px 0 #DA2342}}
[data-glitch="clip"] .glt:hover::before,[data-glitch="clip"] :hover>.glt::before{{animation:gch .5s steps(1) infinite}}
[data-glitch="clip"] .glt:hover::after,[data-glitch="clip"] :hover>.glt::after{{animation:gch .5s steps(1) infinite reverse}}
{polys('gca', 8, 10, idle=.88)}
{polys('gcb', 8, 10, idle=.9)}
{polys('gch', 10, 8)}

@media (prefers-reduced-motion:reduce){{.glt::before,.glt::after{{content:none}}}}
"""

with open(os.path.join(ROOT, 'css', 'glitch.css'), 'w', encoding='utf-8') as f:
    f.write(CSS)
print('wrote css/glitch.css', len(CSS), 'bytes')
